def main():
    out, paths = sys.argv[1], sys.argv[2:]
    sources = [TTFont(p) for p in paths]
    order, glyphs, metrics, cmap = [".notdef", "space"], {}, {}, {}
    glyphs[".notdef"] = TTGlyphPen(None).glyph()
    glyphs["space"] = TTGlyphPen(None).glyph()
    metrics[".notdef"] = metrics["space"] = (UPEM // 2, 0)
    cmap[0xF020] = "space"
    missing = []
    for byte, uni in sorted(WINGDINGS.items()):
        for src in sources:
            name = src.getBestCmap().get(uni)
            if name:
                break
        else:
            missing.append(f"{byte:02X}:U+{uni:04X}")
            continue
        scale = UPEM / src["head"].unitsPerEm
        gn = f"uni{uni:04X}"
        if gn not in glyphs:
            pen = TTGlyphPen(None)
            gs = src.getGlyphSet()
            rec = DecomposingRecordingPen(gs)
            gs[name].draw(rec)
            rec.replay(TransformPen(Cu2QuPen(pen, 1.0, reverse_direction="CFF " in src), (scale, 0, 0, scale, 0, 0)))
            glyphs[gn] = pen.glyph()
            metrics[gn] = (round(gs[name].width * scale), 0)
            order.append(gn)
        cmap[0xF000 + byte] = gn
    if missing:
        print("missing:", " ".join(missing), file=sys.stderr)

    fb = FontBuilder(UPEM, isTTF=True)
    fb.setupGlyphOrder(order)
    fb.setupCharacterMap({})
    fb.setupGlyf(glyphs)
    for gn, g in glyphs.items():
        g.recalcBounds(fb.font["glyf"])
        metrics[gn] = (metrics[gn][0], getattr(g, "xMin", 0))
    fb.setupHorizontalMetrics(metrics)
    fb.setupHorizontalHeader(ascent=1810, descent=-438)
    fb.setupNameTable({"familyName": "Wingdings", "styleName": "Regular",
                       "uniqueFontIdentifier": "demarc Wingdings", "fullName": "Wingdings",
                       "psName": "Wingdings-Regular", "version": "Version 9.00"})
    fb.setupOS2(sTypoAscender=1810, sTypoDescender=-438, usWinAscent=1810, usWinDescent=438,
                ulCodePageRange1=1 << 31, usFirstCharIndex=0xF020, usLastCharIndex=0xF0FE)
    fb.setupPost()
    fb.font["head"].fontRevision = 9.0
    sub = cmap_format_4(4)
    sub.platformID, sub.platEncID, sub.language, sub.cmap = 3, 0, 0, cmap
    fb.font["cmap"].tables = [sub]
    fb.save(out)


main()
