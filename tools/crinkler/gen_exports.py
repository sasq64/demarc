#!/usr/bin/env python3
"""Write system/win/crinkler/exports.txt.

Usage: gen_exports.py <Crinkler repo checkout> <wine i386-windows dir> <out>

Crinkler embeds the export lists it checks tiny-import hashes against
(`known_dll_exports.dat`); each release's copy is found in its binary. Every
name is written once under its DLL, with the versions that list it when that
is not all of them: `Name 23-` (from 2.3 on), `Name 20-22`. DLLs Crinkler has
no list for get the export names of wine's builds, without versions, and
`[winmm ordinals]` gives winmm's names in Windows' ordinal order.
"""

import re
import struct
import sys
from pathlib import Path

# version -> release directory; 2.1a and 2.2 carry the same list as 2.1
# version -> release; the header says "20" for 2.0 and 2.0a alike, and the older
# list has fewer obscure names to take a slot from the function an intro calls
RELEASES = {20: "crinkler20", 21: "crinkler21", 23: "crinkler23", 30: "crinkler30b"}

EXTRA = [
    "opengl32", "ddraw", "d3d8", "dinput", "dinput8", "dxgi", "xinput1_3", "xinput9_1_0",
    "ole32", "oleaut32", "shell32", "shlwapi", "advapi32", "comdlg32", "comctl32", "imm32",
    "msvfw32", "avifil32", "msacm32", "ws2_32", "wsock32", "gdiplus",
] + [f"d3dx9_{n}" for n in range(24, 44)] + [f"d3dx10_{n}" for n in range(33, 44)] + [
    "d3dx11_42", "d3dx11_43", "d3dcompiler_43", "d3dcompiler_47",
]


def find_known(exe: bytes) -> dict[str, list[str]]:
    for m in re.finditer(rb"kernel32\0", exe):
        for p in range(max(0, m.start() - 400000), m.start()):
            n = struct.unpack_from("<i", exe, p)[0]
            if not 5 <= n <= 30:
                continue
            out = {}
            try:
                for i in range(n):
                    no, cnt, tab = struct.unpack_from("<iii", exe, p + 4 + 12 * i)
                    if not 0 < no < 400000 or not 0 < cnt < 5000:
                        raise ValueError
                    name = exe[p + no:exe.index(b"\0", p + no)]
                    if not re.fullmatch(rb"[a-z0-9_]{3,12}", name):
                        raise ValueError
                    names = []
                    for j in range(cnt):
                        o = p + struct.unpack_from("<i", exe, p + tab + 4 * j)[0]
                        names.append(exe[o:exe.index(b"\0", o)].decode())
                    out[name.decode()] = names
            except (ValueError, struct.error):
                continue
            if "kernel32" in out:
                return out
    raise SystemExit("no known export list found")


def pe_exports(path: Path) -> list[str]:
    d = path.read_bytes()
    pe = struct.unpack_from("<I", d, 0x3c)[0]
    nsec, opt = struct.unpack_from("<H", d, pe + 6)[0], struct.unpack_from("<H", d, pe + 20)[0]
    secs = [struct.unpack_from("<IIII", d, pe + 24 + opt + i * 40 + 8) for i in range(nsec)]

    def off(rva):
        for vs, va, rs, ro in secs:
            if va <= rva < va + max(vs, rs):
                return rva - va + ro

    ed = off(struct.unpack_from("<I", d, pe + 24 + 96)[0])
    n, names = struct.unpack_from("<I", d, ed + 24)[0], off(struct.unpack_from("<I", d, ed + 32)[0])
    out = []
    for i in range(n):
        o = off(struct.unpack_from("<I", d, names + 4 * i)[0])
        out.append(d[o:d.index(b"\0", o)].decode())
    return out


def main():
    repo, wine, out = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    lists = {}
    for version, rel in RELEASES.items():
        exe = next(p for p in (repo / "releases" / rel).rglob("*") if p.name.lower() == "crinkler.exe"
                   and "64" not in str(p.parent))
        lists[version] = find_known(exe.read_bytes())
    versions = sorted(lists)
    lines = ["# Generated by tools/crinkler/gen_exports.py; see docs/CRINKLER.md."]
    for dll in sorted({d for k in lists.values() for d in k}):
        lines.append(f"[{dll}]")
        names = sorted({n for k in lists.values() for n in k.get(dll, [])})
        for name in names:
            has = [v for v in versions if name in set(lists[v].get(dll, []))]
            if has == versions:
                lines.append(name)
                continue
            runs = []
            for v in has:
                i = versions.index(v)
                if runs and versions.index(runs[-1][-1]) == i - 1:
                    runs[-1].append(v)
                else:
                    runs.append([v])
            ranges = []
            for run in runs:
                after = versions.index(run[-1]) + 1
                ranges.append(f"{run[0]}-" + (f"{versions[after] - 1}" if after < len(versions) else ""))
            lines.append(f"{name} {','.join(ranges)}")
    # Range imports take the exports after a hashed one by ordinal; winmm's
    # Windows ordinals are not alphabetical (tools/winmm/exports.txt).
    lines.append("[winmm ordinals]")
    winmm = Path(__file__).parent.parent / "winmm" / "exports.txt"
    lines.extend(line.split()[1] for line in winmm.read_text().splitlines() if line.strip())
    for dll in EXTRA:
        lines.append(f"[{dll}]")
        lines.extend(sorted(set(pe_exports(wine / f"{dll}.dll"))))
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
